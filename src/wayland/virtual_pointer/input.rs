/// Scroll state accumulated for one axis between two `frame` requests.
#[derive(Debug, Default, Clone, Copy)]
pub(super) struct PendingAxis {
    pub(super) value: f64,
    /// Discrete steps, if the client sent an `axis_discrete` request for this
    /// axis. [`None`] when it only sent `axis`, which carries no step count.
    pub(super) v120: Option<i32>,
}

/// Scroll state accumulated between two `frame` requests.
#[derive(Debug, Default)]
pub(super) struct PendingFrame {
    pub(super) time: u32,
    pub(super) source: Option<AxisSource>,
    /// Pending state for the horizontal and vertical axes.
    pub(super) axes: [Option<PendingAxis>; 2],
}

pub(super) fn axis_index(axis: Axis) -> usize {
    match axis {
        Axis::Horizontal => 0,
        Axis::Vertical => 1,
    }
}

/// An axis event generated by a virtual pointer, covering one `frame`.
#[derive(Debug)]
pub struct VirtualPointerAxisEvent {
    pub(super) device: VirtualPointerDevice,
    pub(super) frame: PendingFrame,
}

impl input::Event<VirtualPointerBackend> for VirtualPointerAxisEvent {
    fn time(&self) -> InputTime {
        InputTime::from_millis(self.frame.time)
    }

    fn device(&self) -> VirtualPointerDevice {
        self.device.clone()
    }
}

impl input::PointerAxisEvent<VirtualPointerBackend> for VirtualPointerAxisEvent {
    fn amount(&self, axis: Axis) -> Option<f64> {
        self.frame.axes[axis_index(axis)].map(|pending| pending.value)
    }

    fn amount_v120(&self, axis: Axis) -> Option<f64> {
        if !matches!(self.source(), AxisSource::Wheel | AxisSource::WheelTilt) {
            return None;
        }

        // Note this can be `None` for a wheel source, even though the trait
        // says otherwise. A client may send `axis` without `axis_discrete` for
        // a wheel. Don't specify it unless it's non-zero so the compositor
        // falls back to `amount()` if it's unknown.
        self.frame.axes[axis_index(axis)].and_then(|pending| pending.v120.map(f64::from))
    }

    fn source(&self) -> AxisSource {
        // wlroots defaults to wheel when the client doesn't send `axis_source`.
        self.frame.source.unwrap_or(AxisSource::Wheel)
    }

    fn relative_direction(&self, _axis: Axis) -> input::AxisRelativeDirection {
        input::AxisRelativeDirection::Identical
    }
}
